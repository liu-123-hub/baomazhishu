def get_keywords_for_sector(sector_code: str) -> List[str]:
    """获取指定板块的关键词列表。"""
    return SECTOR_KEYWORDS.get(sector_code, [])


def get_all_sector_keywords() -> Dict[str, List[str]]:
    """获取所有板块的关键词配置（用于采集器初始化）。"""
    return dict(SECTOR_KEYWORDS)


def validate_keywords_coverage() -> Dict:
    """验证所有板块都有关键词配置。"""
    missing = []
    for code in SECTOR_NAMES:
        if code not in SECTOR_KEYWORDS or len(SECTOR_KEYWORDS[code]) == 0:
            missing.append(code)
    return {
        "total_sectors": len(SECTOR_NAMES),
        "covered": len(SECTOR_NAMES) - len(missing),
        "missing": missing,
        "is_complete": len(missing) == 0,
    }


