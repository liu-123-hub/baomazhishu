def get_keywords_for_sector(sector_code: str) -> List[str]:
    return SECTOR_KEYWORDS.get(sector_code, [])


def get_all_sector_keywords() -> Dict[str, List[str]]:
    return dict(SECTOR_KEYWORDS)


def validate_keywords_coverage() -> Dict:
    missing = []
    empty = []
    for code in SECTOR_NAMES:
        if code not in SECTOR_KEYWORDS:
            missing.append(code)
        elif len(SECTOR_KEYWORDS[code]) == 0:
            empty.append(code)
    return {
        "total_sectors": len(SECTOR_NAMES),
        "covered": len(SECTOR_NAMES) - len(missing) - len(empty),
        "missing": missing,
        "empty": empty,
        "is_complete": len(missing) == 0 and len(empty) == 0,
        "version": "3.0.0",
        "last_updated": "2026-08-05",
    }


